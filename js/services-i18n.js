/* ------------------------------------------------------------
   DETECTA O IDIOMA PREFERIDO DO NAVEGADOR
   (mesma lógica do i18n.js do projeto principal)
------------------------------------------------------------ */
function detectarIdioma() {
  const salvo = localStorage.getItem('idioma-preferido');
  if (salvo && traducoes[salvo]) return salvo;

  const idiomas = navigator.languages || [navigator.language || 'en'];
  for (const idioma of idiomas) {
    const codigo = idioma.toLowerCase().split('-')[0];
    if (traducoes[codigo]) return codigo;
  }
  return 'en';
}


/* ------------------------------------------------------------
   APLICA AS TRADUÇÕES NA PÁGINA
------------------------------------------------------------ */
function aplicarIdioma(lang) {
  const t = traducoes[lang];
  if (!t) return;

  /* Título da aba */
  document.title = t.pageTitle;

  /* Atributo lang do <html> */
  document.documentElement.lang = lang === 'pt' ? 'pt-BR' : lang;

  /* Elementos com data-i18n="chave" — troca o texto simples */
  document.querySelectorAll('[data-i18n]').forEach(function(el) {
    const chave = el.dataset.i18n;
    if (t[chave] !== undefined) el.textContent = t[chave];
  });

  /* Elementos com data-i18n-html="chave" — troca o HTML interno
     (usado no título hero que tem um <span> de destaque colorido) */
  document.querySelectorAll('[data-i18n-html]').forEach(function(el) {
    const chave = el.dataset.i18nHtml;
    if (t[chave] !== undefined) el.innerHTML = t[chave];
  });
}


